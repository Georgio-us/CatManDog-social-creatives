"""Bundle local CatManDog image assets for file:// canvas export."""

from base64 import b64encode
from io import BytesIO
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent
SOURCES = {
    "logo": ROOT / "assets/brand/CatManDog-wordmark-black-transparent.png",
    "symbol": ROOT / "assets/brand/CatManDog-symbol-black-transparent.png",
    "catup": ROOT / "assets/reference/cat-looking-up.png",
    "foodpair": ROOT / "assets/reference/food-compare.png",
    "play": ROOT / "assets/reference/cat-playing.png",
    "catcare": ROOT / "assets/reference/cat-care.png",
    "toys": ROOT / "assets/reference/toys.png",
}


def main():
    entries = []
    for name, path in SOURCES.items():
        image = Image.open(path).convert("RGBA")
        image.thumbnail((1350, 1600), Image.Resampling.LANCZOS)
        output = BytesIO()
        image.save(output, format="WEBP", quality=88, method=6)
        data = b64encode(output.getvalue()).decode("ascii")
        entries.append(f'  {name}: "data:image/webp;base64,{data}"')
    (ROOT / "embedded-assets.js").write_text(
        "// Generated by build_assets.py from local CatManDog assets\n"
        "window.CMD_EMBEDDED_ASSETS = {\n" + ",\n".join(entries) + "\n};\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
